"""Inventory, measure, delete, and ratchet the code comments of a repository.

Usage:
    comments.py inventory [PATH ...] [--kinds KINDS] [--format jsonl|tsv]
    comments.py estimate [PATH ...] [--verdicts FILE] [--json]
    comments.py delete --verdicts FILE [--dry-run]
    comments.py ratchet init [PATH ...] [--exclude GLOB ...] [--ban-doc] [--message TEXT]
    comments.py ratchet check [FILE ...] [--allow-stale] [--base REF]
    comments.py ratchet update [FILE ...] [--allow-increase] [--base REF]

Every command takes --config FILE (default: .comment-ratchet.json in the current directory,
when it exists) and --jobs N. Paths in the output and in the config are relative to the
directory that holds the config, or to the current directory when there is no config.

pygments lexes each file, so a comment marker inside a string or a regex literal is not a
comment. Each comment gets one kind:

    directive  a tool reads it: a shebang, an encoding cookie, PEP 723 metadata, a lint,
               type-check, format, coverage, or secret-scanner directive, a build constraint,
               a compiler pragma. The list errs toward keeping: a false directive keeps one
               comment, a missed one deletes something a tool needs.
    license    a copyright or license notice
    doc        a documentation comment: /** */, ///, //!, /*!, a Go comment on a declaration,
               a Sphinx #: comment, or a comment with @param-style tags
    plain      everything else

Consecutive full-line comments of one kind at one indentation form one item. A placement
is full-line (nothing else on its lines), trailing (code before it), or inline (code after
it). Only full-line items free lines when deleted.

The scanner skips files that are binary, larger than 2 MB, not UTF-8, generated (a
"@generated", "DO NOT EDIT", or "Generated by" marker in the first five lines), minified,
in a vendored directory, without a pygments lexer, or prose and data (Markdown, reST, text,
JSON, XML, diffs). Python docstrings are string literals, not comments, so they are code.

delete removes the items that a verdicts file (JSONL: inventory records plus "category" and
"ref") allows: tautology and stale always, excuse only with an issue ref (a URL, owner/repo#N,
#N, a KEY-N tracker key, or an existing file), decision only with a ref that is a URL or an
existing path (the ADR, or the test or code that now encodes
the fact). It never removes a directive or license item. Before it writes a file, it lexes
the result again and requires the same code tokens; for Python it also requires the same
AST. A file that fails the check is left unchanged.

Exit status: 0 success, 1 a check failed or something needs attention, 2 usage error.
"""

