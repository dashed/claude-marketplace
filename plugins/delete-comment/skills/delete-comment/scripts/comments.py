def is_comment(token: Any, value: str) -> bool:
    if token in Comment:
        return token not in Comment.Preproc and token not in Comment.PreprocFile
    return token in String.Doc and value.lstrip().startswith(("//", "/*", "#", "--", "(*", "{-"))


def continues(text: str) -> bool:
    """Tell whether the next contiguous comment token belongs to this comment."""
    for opener, closer in BLOCK_DELIMITERS:
        if text.startswith(opener):
            return not (len(text) >= len(opener) + len(closer) and text.endswith(closer))
    return not text.endswith("\n")


def body(text: str) -> str:
    return END_MARKER.sub("", MARKER.sub("", text.lstrip(), count=1)).strip()


def segments(text: str) -> list[str]:
    if text.startswith("#") and not text.startswith(("#|", "#[")):
        return re.split(r"\s+(?=#)", text)
    return [text]


def classify(raw: Raw, language: str, options: Options, at_file_start: bool) -> None:
    text = raw.text
    if at_file_start and text.startswith("#!"):
        raw.kind, raw.reason = "directive", "shebang"
        return
    for reason, pattern in RAW_DIRECTIVES:
        if pattern.search(text):
            raw.kind, raw.reason = "directive", reason
            return
    if language == "Makefile" and text.startswith("##"):
        raw.kind, raw.reason = "directive", "make help text"
        return
    if language in ("JavaScript", "JSX") and text.startswith("/**") and JSDOC_TYPES.search(text):
        raw.kind, raw.reason = "directive", "JSDoc type annotation"
        return
    found = ""
    prose = False
    anchored = [
        (reason, pattern)
        for reason, pattern in ANCHORED_DIRECTIVES
        if language in LANGUAGE_ONLY.get(reason, (language,))
    ]
    for segment in segments(text):
        segment_body = body(segment)
        reason = next((r for r, p in anchored if p.match(segment_body)), "")
        reason = reason or next((r for r, p in ANYWHERE_DIRECTIVES if p.search(segment)), "")
        if not reason and any(re.search(pattern, segment) for pattern in options.allow):
            reason = "allowed by config"
        if reason:
            found = found or reason
        elif re.search(r"[A-Za-z]", segment_body):
            prose = True
    if found:
        raw.kind, raw.reason, raw.prose = "directive", found, prose
    elif LICENSE.search(text):
        raw.kind, raw.reason = "license", "license notice"
    elif raw.doc_token or (text.startswith("/**") and not text.startswith("/**/")):
        raw.kind, raw.reason = "doc", "doc comment"
    elif text.startswith(("///", "//!", "/*!")):
        raw.kind, raw.reason = "doc", "doc comment"
    elif language == "Python" and text.startswith("#:"):
        raw.kind, raw.reason = "doc", "Sphinx attribute comment"
    elif text.startswith("<#") and re.search(r"\.(SYNOPSIS|DESCRIPTION)\b", text):
        raw.kind, raw.reason = "doc", "PowerShell comment-based help"


def line_starts(text: str) -> list[int]:
    return [0, *(match.end() for match in re.finditer("\n", text))]


def line_count(text: str) -> int:
    if not text:
        return 0
    return text.count("\n") + (0 if text.endswith("\n") else 1)


def line_text(text: str, starts: list[int], line: int) -> str:
    if line > len(starts):
        return ""
    end = starts[line] if line < len(starts) else len(text)
    return text[starts[line - 1] : end]


def hints(item: Item) -> list[str]:
    found = []
    if TODO_HINT.search(item.text):
        found.append("todo")
    if EXCUSE_HINT.search(item.text):
        found.append("excuse")
    bodies = [body(line) for line in item.text.splitlines() if body(line)]
    if bodies and sum(bool(CODE_HINT.search(b)) for b in bodies) * 2 >= len(bodies):
        found.append("code")
    if bodies and all(DIVIDER_HINT.search(b) for b in bodies[:1]):
        found.append("divider")
    return found


def joinable(previous: Raw, raw: Raw, language: str) -> bool:
    if raw.line > previous.end_line + 1 or raw.column != previous.column:
        return False
    if "directive" in (previous.kind, raw.kind) or (previous.kind == "doc") != (raw.kind == "doc"):
        return False
    if language == "Python" and (body(previous.text) == "///" or PEP723_OPEN.match(body(raw.text))):
        return False
    return True


def group_item(group: list[Raw], path: str, language: str, text: str, starts: list[int]) -> Item:
    first, last = group[0], group[-1]
    joined = "\n".join(raw.text for raw in group)
    kinds = {raw.kind for raw in group}
    kind, reason = first.kind, first.reason
    if "license" in kinds or LICENSE.search(joined):
        kind, reason = "license", "license notice"
    elif language == "Python" and PEP723_OPEN.match(body(first.text)):
        kind, reason = "directive", "PEP 723 metadata"
    elif kind == "plain" and first.placement == "full-line":
        if language == "Go" and GO_DECLARATION.match(line_text(text, starts, last.end_line + 1)):
            kind, reason = "doc", "Go doc comment"
        elif any(DOC_TAGS.match(body(line)) for line in joined.splitlines()):
            kind, reason = "doc", "doc tags"
    lines = last.end_line - first.line + 1 if first.placement == "full-line" else 0
    item = Item(
        path=path,
        language=language,
        line=first.line,
        end_line=last.end_line,
        column=first.column + 1,
        kind=kind,
        placement=first.placement,
        lines=lines,
        text=joined,
        reason=reason,
        prose=any(raw.prose for raw in group),
        spans=[(raw.start, raw.end) for raw in group],
    )
    if kind in DELETABLE_KINDS:
        item.hints = hints(item)
    return item


def scan_text(text: str, path: str, lexer: Any, options: Options) -> FileScan:
    language = lexer.name
    tokens = list(lexer.get_tokens_unprocessed(text))
    if "".join(value for _, _, value in tokens) != text:
        return FileScan(path, "lexer-mismatch", language)
    starts = line_starts(text)
    first_code = [sys.maxsize] * (len(starts) + 2)
    last_code = [-1] * (len(starts) + 2)
    raws: list[Raw] = []
    for index, token, value in tokens:
        if is_comment(token, value):
            if raws and raws[-1].end == index and continues(raws[-1].text):
                raws[-1].text += value
                raws[-1].end += len(value)
            else:
                raws.append(Raw(index, index + len(value), value, token in String.Doc))
            continue
        stripped = value.strip(BLANK)
        if stripped:
            low = index + len(value) - len(value.lstrip(BLANK))
            high = low + len(stripped)
        elif token in String:
            low, high = index, index + len(value)
        else:
            continue
        for line in range(bisect_right(starts, low), bisect_right(starts, high - 1) + 1):
            line_end = starts[line] if line < len(starts) else high
            first_code[line] = min(first_code[line], max(low, starts[line - 1]))
            last_code[line] = max(last_code[line], min(high, line_end))
    bom = 1 if text.startswith("\ufeff") else 0
    for raw in raws:
        trimmed = raw.text.rstrip("\r\n")
        raw.end -= len(raw.text) - len(trimmed)
        raw.text = trimmed
        raw.line = bisect_right(starts, raw.start)
        raw.end_line = bisect_right(starts, max(raw.start, raw.end - 1))
        raw.column = raw.start - starts[raw.line - 1]
        before = first_code[raw.line] < raw.start
        after = last_code[raw.end_line] > raw.end
        raw.placement = "inline" if after else "trailing" if before else "full-line"
        classify(raw, language, options, raw.start == bom)
    items: list[Item] = []
    group: list[Raw] = []
    for raw in raws:
        grouped = raw.placement == "full-line" and raw.kind != "directive"
        if grouped and group and joinable(group[-1], raw, language):
            group.append(raw)
            continue
        if group:
            items.append(group_item(group, path, language, text, starts))
        group = [raw] if grouped else []
        if not grouped:
            items.append(group_item([raw], path, language, text, starts))
    if group:
        items.append(group_item(group, path, language, text, starts))
    seen: Counter[str] = Counter()
    for item in items:
        occurrence = seen[item.text]
        seen[item.text] += 1
        digest = hashlib.sha1(f"{path}\0{occurrence}\0{item.text}".encode()).hexdigest()
        item.id = digest[:12]
    total = line_count(text)
    code_lines = sum(1 for line in range(1, total + 1) if last_code[line] >= 0)
    comment_only = {
        line
        for raw in raws
        if raw.placement == "full-line"
        for line in range(raw.line, raw.end_line + 1)
    }
    blank = total - code_lines - len(comment_only)
    return FileScan(path, "scanned", language, total, code_lines, blank, items)


def find_lexer(path: str, text: str) -> Any:
    try:
        return get_lexer_for_filename(Path(path).name, code=text[:20000])
    except ClassNotFound:
        return None


def scan_file(root: str, path: str, options: Options) -> FileScan:
    try:
        data = Path(root, path).read_bytes()
    except OSError:
        return FileScan(path, "unreadable")
    if len(data) > MAX_BYTES:
        return FileScan(path, "too-large")
    if b"\0" in data[:8192]:
        return FileScan(path, "binary")
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return FileScan(path, "not-utf8")
    if path.endswith(SKIP_SUFFIXES):
        return FileScan(path, "minified")
    if GENERATED.search("\n".join(text.splitlines()[:5])):
        return FileScan(path, "generated")
    lexer = find_lexer(path, text)
    if lexer is None:
        return FileScan(path, "no-lexer")
    if lexer.name in SKIP_LEXERS:
        return FileScan(path, "prose-or-data", lexer.name)
    if options.languages and lexer.name.lower() not in options.languages:
        return FileScan(path, "language-filtered", lexer.name)
    return scan_text(text, path, lexer, options)


def excluded(path: str, patterns: list[str]) -> bool:
    if SKIP_DIRS.intersection(Path(path).parts[:-1]):
        return True
    return any(fnmatch.fnmatch(path, pattern) for pattern in patterns)


def list_files(root: Path, paths: list[str], exclude: list[str]) -> list[str]:
    found: set[str] = set()
    directories: list[str] = []
    for entry in paths:
        target = (root / entry).resolve()
        relative = os.path.relpath(target, root.resolve())
        if target.is_file():
            found.add(Path(relative).as_posix())
        elif target.is_dir():
            directories.append(relative)
        else:
            raise UsageError(f"no such file or directory: {entry}")
    if directories:
        command = ["git", "-C", str(root), "ls-files", "-z", "--cached", "--others"]
        command += ["--exclude-standard", "--", *directories]
        try:
            output = subprocess.run(command, capture_output=True, check=True).stdout
            found.update(name for name in output.decode("utf-8", "replace").split("\0") if name)
        except (OSError, subprocess.CalledProcessError):
            for directory in directories:
                for current, subdirs, files in os.walk(root / directory):
                    subdirs[:] = [name for name in subdirs if name not in SKIP_DIRS]
                    for name in files:
                        found.add(Path(os.path.relpath(Path(current, name), root)).as_posix())
    return sorted(path for path in found if (root / path).is_file() and not excluded(path, exclude))


def scan_paths(config: Config, paths: list[str], jobs: int) -> list[FileScan]:
    files = list_files(config.root, paths, config.exclude)
    options = config.options()
    if jobs <= 1 or len(files) < 64:
        return [scan_file(str(config.root), path, options) for path in files]
    with ProcessPoolExecutor(max_workers=jobs) as pool:
        work = pool.map(scan_file, repeat(str(config.root)), files, repeat(options), chunksize=32)
        return list(work)


def load_config(location: str | None, required: bool = False) -> Config:
    if location is None:
        default = Path(DEFAULT_CONFIG)
        if not default.is_file():
            if required:
                raise UsageError(f"no {DEFAULT_CONFIG}: run `ratchet init` first")
            return Config(root=Path.cwd())
        location = str(default)
    path = Path(location)
    if not path.is_file():
        raise UsageError(f"config not found: {location}")
    data = json.loads(path.read_text())
    unknown = set(data.get("ban", [])) - set(DELETABLE_KINDS)
    if unknown:
        raise UsageError(f"ban may list only {', '.join(DELETABLE_KINDS)}: {sorted(unknown)}")
    return Config(
        root=path.resolve().parent,
        path=path,
        paths=list(data.get("paths", ["."])),
        exclude=list(data.get("exclude", [])),
        ban=list(data.get("ban", ["plain"])),
        allow=list(data.get("allow", [])),
        languages=list(data.get("languages", [])),
        message=data.get("message", DEFAULT_MESSAGE),
        files={str(k): int(v) for k, v in data.get("files", {}).items()},
    )


def scope(config: Config, paths: list[str]) -> list[str]:
    if not paths:
        return config.paths
    return [os.path.relpath(Path(path).resolve(), config.root.resolve()) for path in paths]


def first_line(text: str, width: int = 100) -> str:
    line = text.splitlines()[0] if text else ""
    return line if len(line) <= width else line[: width - 1] + "…"


def command_inventory(args: argparse.Namespace) -> int:
    config = load_config(args.config)
    kinds = KINDS if args.kinds == "all" else tuple(args.kinds.split(","))
    if set(kinds) - set(KINDS):
        raise UsageError(f"--kinds takes all or a comma list of {', '.join(KINDS)}")
    for scan in scan_paths(config, scope(config, args.paths), args.jobs):
        for item in scan.items:
            if item.kind not in kinds:
                continue
            if args.format == "tsv":
                fields = [f"{item.path}:{item.line}", item.id, item.kind, item.placement]
                fields += [",".join(item.hints) or "-", first_line(item.text)]
                print("\t".join(fields))
            else:
                print(json.dumps(item.record(), ensure_ascii=False))
    return 0


def read_verdicts(path: str) -> list[dict[str, Any]]:
    verdicts = []
    for number, line in enumerate(Path(path).read_text().splitlines(), 1):
        if not line.strip():
            continue
        try:
            verdict = json.loads(line)
        except json.JSONDecodeError as error:
            raise UsageError(f"{path}:{number}: not JSON: {error}") from error
        if not {"id", "path", "category"} <= verdict.keys():
            raise UsageError(f"{path}:{number}: a verdict needs id, path, and category")
        if verdict["category"] not in CATEGORIES:
            raise UsageError(f"{path}:{number}: category must be one of {', '.join(CATEGORIES)}")
        verdicts.append(verdict)
    return verdicts


def estimate(scans: list[FileScan], verdicts: list[dict[str, Any]]) -> dict[str, Any]:
    scanned = [scan for scan in scans if scan.status == "scanned"]
    by_kind = {kind: {"items": 0, "lines": 0, "trailing_or_inline": 0} for kind in KINDS}
    for scan in scanned:
        for item in scan.items:
            bucket = by_kind[item.kind]
            bucket["items"] += 1
            bucket["lines"] += item.lines
            bucket["trailing_or_inline"] += item.placement != "full-line"
    total = sum(scan.lines for scan in scanned)
    report: dict[str, Any] = {
        "files_scanned": len(scanned),
        "files_skipped": dict(Counter(scan.status for scan in scans if scan.status != "scanned")),
        "generated_files": [scan.path for scan in scans if scan.status == "generated"],
        "languages": dict(Counter(scan.language for scan in scanned).most_common()),
        "lines": {
            "total": total,
            "code": sum(scan.code_lines for scan in scanned),
            "blank": sum(scan.blank_lines for scan in scanned),
            "comment_only": total - sum(scan.code_lines + scan.blank_lines for scan in scanned),
        },
        "kinds": by_kind,
        "if_deleted": {
            "plain": by_kind["plain"]["lines"],
            "plain_and_doc": by_kind["plain"]["lines"] + by_kind["doc"]["lines"],
        },
    }
    if verdicts:
        items = {item.id: item for scan in scanned for item in scan.items}
        categories = {c: {"items": 0, "lines": 0} for c in CATEGORIES}
        missing = 0
        for verdict in verdicts:
            item = items.get(verdict["id"])
            if item is None:
                missing += 1
                continue
            categories[verdict["category"]]["items"] += 1
            categories[verdict["category"]]["lines"] += item.lines
        classified = {v["id"] for v in verdicts}
        unclassified = [
            item for item in items.values() if item.kind == "plain" and item.id not in classified
        ]
        report["categories"] = categories
        report["unclassified_plain"] = {
            "items": len(unclassified),
            "lines": sum(item.lines for item in unclassified),
        }
        report["verdicts_not_found"] = missing
    return report


def percent(part: int, whole: int) -> str:
    return f"{100 * part / whole:.1f}%" if whole else "0%"


